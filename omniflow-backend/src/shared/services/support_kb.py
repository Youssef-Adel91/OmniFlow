def _tokens(text: str) -> list[str]:
    return [t for t in norm_text(text).split() if len(t) > 1]


def search(query: str, limit: int = 5) -> list[dict]:
    """Rank articles for a free-text Arabic/English query. Title hits weigh most, then keywords, then the answer text."""
    q = _tokens(query)
    if not q:
        return []
    scored: list[tuple[float, Article]] = []
    for a in ARTICLES:
        title, kws, body = norm_text(a.title), [norm_text(k) for k in a.keywords], norm_text(a.answer)
        score = 0.0
        for t in q:
            if t in title.split():
                score += 3
            elif t in title:
                score += 1.5
            if any(t == k or (len(t) > 2 and t in k) or (len(k) > 2 and k in t) for k in kws):
                score += 2
            if t in body:
                score += 0.5
        if score > 0:
            scored.append((score, a))
    scored.sort(key=lambda x: (-x[0], x[1].id))
    return [{"id": a.id, "title": a.title, "answer": a.answer, "category": a.category, "link": a.link, "link_label": a.link_label, "score": round(s, 1)}
            for s, a in scored[:limit]]


def all_articles() -> list[dict]:
    return [{"id": a.id, "title": a.title, "answer": a.answer, "category": a.category, "link": a.link, "link_label": a.link_label} for a in ARTICLES]
